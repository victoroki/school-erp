    /**
     * Assemble the pure-array input for the generator from the database.
     */
    private function generateTimetable(int $academicYearId): TimetableGenerationResult
    {
        $classSections = ClassSection::with(['class', 'section'])
            ->where('academic_year_id', $academicYearId)
            ->orderBy('class_id')
            ->orderBy('section_id')
            ->get();

        $periods = Period::where('type', 'period')
            ->orderBy('start_time')
            ->get(['period_id', 'start_time', 'name']);

        $classSubjects = ClassSubject::where('academic_year_id', $academicYearId)->get()->toArray();
        $teacherSubjects = \App\Models\TeacherSubject::where('academic_year_id', $academicYearId)->get()->toArray();

        $subjects = \App\Models\Subject::pluck('name', 'subject_id')->toArray();
        $teachers = \App\Models\Staff::where('staff_type', 'teaching')
            ->active()
            ->get()
            ->mapWithKeys(function ($staff) {
                return [$staff->staff_id => trim($staff->first_name . ' ' . $staff->middle_name . ' ' . $staff->last_name)];
            })
            ->toArray();
        $classrooms = \App\Models\Classroom::pluck('room_number', 'classroom_id')->toArray();

        $existing = Timetable::where('academic_year_id', $academicYearId)->get()->toArray();

        $service = new TimetableGeneratorService();

        return $service->generate([
            'academic_year_id' => $academicYearId,
            'class_sections' => $classSections->map(function ($cs) {
                return [
                    'id' => $cs->class_section_id,
                    'class_id' => $cs->class_id,
                    'classroom_id' => $cs->classroom_id,
                    'label' => trim(($cs->class->name ?? '') . ' - ' . ($cs->section->name ?? '')),
                ];
            })->values()->toArray(),
            'periods' => $periods->map(function ($period) {
                return ['id' => $period->period_id, 'start_time' => $period->start_time, 'name' => $period->name];
            })->values()->toArray(),
            'class_subjects' => $classSubjects,
            'teacher_subjects' => $teacherSubjects,
            'subjects' => $subjects,
            'teachers' => $teachers,
            'classrooms' => $classrooms,
            'existing' => $existing,
        ]);
    }

    /**
     * Build per-class-section weekly grids for the preview view.
     */
    private function buildPreview(TimetableGenerationResult $result, int $academicYearId): array
    {
        $periods = Period::where('type', 'period')->orderBy('start_time')->get(['period_id', 'name', 'start_time']);
        $daysOfWeek = [
            'monday' => 'Monday',
            'tuesday' => 'Tuesday',
            'wednesday' => 'Wednesday',
            'thursday' => 'Thursday',
            'friday' => 'Friday',
            'saturday' => 'Saturday',
            'sunday' => 'Sunday',
        ];

        $subjectNames = \App\Models\Subject::pluck('name', 'subject_id');
        $teacherNames = \App\Models\Staff::all()->mapWithKeys(function ($staff) {
            return [$staff->staff_id => trim($staff->first_name . ' ' . $staff->last_name)];
        });
        $classroomNumbers = \App\Models\Classroom::pluck('room_number', 'classroom_id');
        $sectionLabels = ClassSection::with(['class', 'section'])
            ->where('academic_year_id', $academicYearId)
            ->get()
            ->mapWithKeys(function ($cs) {
                return [$cs->class_section_id => trim(($cs->class->name ?? '') . ' - ' . ($cs->section->name ?? ''))];
            });

        $schedules = [];
        foreach ($result->placements as $row) {
            $csId = (int) $row['class_section_id'];
            if (!isset($schedules[$csId])) {
                $schedules[$csId] = [
                    'label' => $sectionLabels[$csId] ?? 'Section #' . $csId,
                    'grid' => [],
                ];
            }
            $schedules[$csId]['grid'][$row['day_of_week']][(int) $row['period_id']] = [
                'subject' => $subjectNames[$row['subject_id']] ?? 'Subject #' . $row['subject_id'],
                'teacher' => $teacherNames[$row['teacher_id']] ?? 'Teacher #' . $row['teacher_id'],
                'classroom' => $classroomNumbers[$row['classroom_id']] ?? 'Room',
            ];
        }

        return [
            'periods' => $periods,
            'daysOfWeek' => $daysOfWeek,
            'schedules' => $schedules,
        ];
    }

    /**
     * Get data needed for create/edit forms
     */
    private function getFormData(): array
    {
        return [
            'classSections' => ClassSection::with(['class', 'section', 'academicYear'])
                ->get()
                ->mapWithKeys(function ($item) {
                    $className = $item->class->name ?? 'Unknown Class';
                    $sectionName = $item->section->name ?? 'Unknown Section';
                    return [$item->class_section_id => $className . ' - ' . $sectionName];
                })
                ->toArray(),

            'periods' => Period::where('type', 'period')
                ->orderBy('start_time')
                ->pluck('name', 'period_id')
                ->toArray(),

            'subjects' => Subject::orderBy('name')
                ->pluck('name', 'subject_id')
                ->toArray(),

            'teachers' => Staff::where('staff_type', 'teaching')
                ->active()
                ->orderBy('first_name')
                ->get()
                ->mapWithKeys(function ($staff) {
                    $name = trim($staff->first_name . ' ' . $staff->middle_name . ' ' . $staff->last_name);
                    if ($staff->employee_id) {
                        $name .= ' (' . $staff->employee_id . ')';
                    }
                    return [$staff->staff_id => $name];
                })
                ->toArray(),

            'classrooms' => Classroom::pluck('room_number', 'classroom_id')
                ->toArray(),

            'academicYears' => AcademicYear::orderBy('start_date', 'desc')
                ->pluck('name', 'academic_year_id')
                ->toArray(),

            'daysOfWeek' => [
                'monday' => 'Monday',
                'tuesday' => 'Tuesday',
                'wednesday' => 'Wednesday',
                'thursday' => 'Thursday',
                'friday' => 'Friday',
                'saturday' => 'Saturday',
                'sunday' => 'Sunday'
            ]
        ];
    }
