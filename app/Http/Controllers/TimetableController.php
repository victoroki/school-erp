                    'label' => $label,
                ];
            });

        return response()->json($classSections);
    }


    /**
     * Get teachers for a specific subject (AJAX).
     * Deduplicates staff across multiple class-section assignments for the same subject.
     * Optionally narrows by class_section_id and/or academic_year_id query params.
     */
    public function getTeachersBySubject(Request $request, $subjectId)
    {
        $classSectionId  = $request->get('class_section_id');
        $academicYearId  = $request->get('academic_year_id');

        $query = \App\Models\TeacherSubject::with('staff')
            ->where('subject_id', $subjectId);

        if ($classSectionId) {
            $query->where('class_section_id', $classSectionId);
        }

        if ($academicYearId) {
            $query->where('academic_year_id', $academicYearId);
        }

        // Deduplicate by staff_id so one teacher appearing in multiple rows shows only once
        $teachers = $query->get()
            ->filter(fn($item) => $item->staff !== null)
            ->unique('staff_id')
            ->map(function ($item) {
                $staff = $item->staff;
                $name  = trim(
                    $staff->first_name . ' ' .
                    ($staff->middle_name ? $staff->middle_name . ' ' : '') .
                    $staff->last_name
                );
                if ($staff->employee_id) {
                    $name .= ' (' . $staff->employee_id . ')';
                }
                return ['id' => $staff->staff_id, 'name' => $name];
            })
            ->values(); // re-index to a clean JSON array

        return response()->json($teachers);
    }

    /**
     * Preview an auto-generated weekly timetable for one academic year.
     * Nothing is saved here — the admin must confirm via storeAutoGenerated.
     */
    public function autoGenerate(Request $request)
    {
        $academicYears = AcademicYear::orderBy('start_date', 'desc')->get();

        $selectedAcademicYearId = $request->get('academic_year_id');
        if (!$selectedAcademicYearId && $academicYears->count() > 0) {
            $current = $academicYears->firstWhere('is_current', true);
            $selectedAcademicYearId = $current ? $current->academic_year_id : $academicYears->first()->academic_year_id;
        }

        $classSubjectOptions = collect();
        if ($selectedAcademicYearId) {
            $classSubjectOptions = ClassSubject::with(['class', 'subject.department'])
                ->where('academic_year_id', $selectedAcademicYearId)
                ->orderBy('class_id')
                ->orderBy('subject_id')
                ->get();
        }

        $preview = null;
        $result = null;

        if ($selectedAcademicYearId && $request->boolean('preview')) {
            $result = $this->generateTimetable((int) $selectedAcademicYearId);
            $preview = $this->buildPreview($result, (int) $selectedAcademicYearId);
        }

        return view('timetables.auto_generate', [
            'academicYears' => $academicYears,
            'academicYearOptions' => $academicYears->pluck('name', 'academic_year_id'),
            'selectedAcademicYearId' => $selectedAcademicYearId,
            'classSubjectOptions' => $classSubjectOptions,
            'result' => $result,
            'preview' => $preview,
        ]);
    }

    /**
     * Persist per-subject weekly period counts for an academic year, then
     * regenerate the preview so the admin can review before confirming.
     */
    public function saveAutoGenerateOptions(Request $request)
    {
        $academicYearId = (int) $request->input('academic_year_id');
        $periods = $request->input('periods', []); // [class_subject_id => count]

        foreach ($periods as $id => $count) {
            $classSubject = ClassSubject::where('academic_year_id', $academicYearId)->find($id);
            if (!$classSubject) {
                continue;
            }
            $classSubject->periods_per_week = max(1, min(40, (int) $count));
            $classSubject->save();
        }

        Flash::success('Weekly period settings saved. Review the preview below, then confirm.');
        return redirect(route('timetables.auto-generate', [
            'academic_year_id' => $academicYearId,
            'preview' => 1,
        ]));
    }

    /**
     * Persist a previously-previewed auto-generated timetable.
     * Regenerates server-side (never trusts the client), replaces the
     * academic year's lessons within a transaction, validates each row
     * through the model, and audits the change. Also auto-generates
     * term weeks if none exist yet.
     */
    public function storeAutoGenerated(Request $request)
    {
        $academicYearId = (int) $request->input('academic_year_id');

        $academicYear = AcademicYear::find($academicYearId);
        if (!$academicYear) {
            Flash::error('Academic year not found.');
            return redirect(route('timetables.auto-generate'));
        }

        $result = $this->generateTimetable($academicYearId);

        if ($result->placedCount() === 0) {
            Flash::warning('Auto-generation produced no lessons. Check that periods, class sections, subjects and teacher assignments exist.');
            return redirect(route('timetables.auto-generate', ['academic_year_id' => $academicYearId]));
        }

        // Auto-generate term weeks if none exist for this academic year
        $existingWeekCount = TermWeek::where('academic_year_id', $academicYearId)->count();
        if ($existingWeekCount === 0) {
            $this->generateTermWeeksForYear($academicYearId);
        }

        $oldData = Timetable::where('academic_year_id', $academicYearId)->get()->toArray();
        $savedCount = 0;
        $validationErrors = [];

        DB::transaction(function () use ($academicYearId, $result, &$savedCount, &$validationErrors) {
            Timetable::where('academic_year_id', $academicYearId)->delete();

            foreach ($result->placements as $idx => $row) {
                // Validate through the model before inserting
                $timetable = new Timetable();
                $timetable->fill($row);

                $validator = \Illuminate\Support\Facades\Validator::make(
                    $timetable->toArray(),
                    [
                        'class_section_id' => 'required|exists:class_sections,class_section_id',
                        'day_of_week' => 'required|string|in:monday,tuesday,wednesday,thursday,friday,saturday,sunday',
                        'period_id' => 'required|exists:periods,period_id',
                        'subject_id' => 'required|exists:subjects,subject_id',
                        'teacher_id' => 'required|exists:staff,staff_id',
                        'classroom_id' => 'required|exists:classrooms,classroom_id',
                        'academic_year_id' => 'required|exists:academic_years,academic_year_id',
                    ]
                );

                if ($validator->fails()) {
                    $validationErrors[] = "Row " . ($idx + 1) . ": " . $validator->errors()->first();
                    continue;
                }

                $timetable->save();
                $savedCount++;
            }
        });

        AuditTrail::log('Timetable', 'AUTO_GENERATE', null, $oldData, [
            'academic_year_id' => $academicYearId,
            'placed' => $savedCount,
            'unplaced' => $result->unplaced,
            'validation_errors' => $validationErrors,
        ]);

        $messages = [];
        if ($savedCount > 0) {
            $messages[] = $savedCount . ' lessons generated successfully.';
        }
        if ($result->unplacedCount() > 0) {
            $messages[] = $result->unplacedCount() . ' could not be placed (see details).';
        }
        if (!empty($validationErrors)) {
            $messages[] = count($validationErrors) . ' rows had validation errors.';
        }

        Flash::warning(implode(' ', $messages) ?: 'No lessons were generated.');

        return redirect(route('timetables.index', ['academic_year_id' => $academicYearId]));
    }

    /**
     * Auto-generate term weeks for all terms in an academic year.
     */
    private function generateTermWeeksForYear(int $academicYearId): void
    {
        $terms = \App\Models\Term::where('academic_year_id', $academicYearId)->get();
        foreach ($terms as $term) {
            $weeks = TermWeek::generateForTerm($term);
            foreach ($weeks as $weekData) {
                TermWeek::create($weekData);
            }
        }
    }

    /**
     * AJAX: Check for conflicts when assigning a teacher/classroom to a slot.
     * Reuses TimetableConflictService directly — no duplicated logic.
     */
    public function checkConflict(Request $request)
    {
        $request->validate([
            'academic_year_id' => 'required|integer|exists:academic_years,academic_year_id',
            'term_week_id' => 'required|integer|exists:term_weeks,id',
            'teacher_id' => 'required|integer|exists:staff,staff_id',
            'day_of_week' => 'required|string|in:monday,tuesday,wednesday,thursday,friday,saturday,sunday',
            'period_id' => 'required|integer|exists:periods,period_id',
            'class_section_id' => 'nullable|integer|exists:class_sections,class_section_id',
            'classroom_id' => 'nullable|integer|exists:classrooms,classroom_id',
            'ignore_timetable_id' => 'nullable|integer',
        ]);

        $academicYearId = (int) $request->input('academic_year_id');
        $termWeekId = (int) $request->input('term_week_id');
        $teacherId = (int) $request->input('teacher_id');
        $day = $request->input('day_of_week');
        $periodId = (int) $request->input('period_id');
        $ignoreId = $request->input('ignore_timetable_id') ? (int) $request->input('ignore_timetable_id') : null;

        $conflicts = [];
        $warnings = [];

        // Teacher conflict on effective schedule
        $teacherResult = TimetableConflictService::effectiveTeacherConflict(
            $academicYearId, $termWeekId, $teacherId, $day, $periodId, $ignoreId
        );
        if ($teacherResult) {
            $conflicts['teacher'] = $teacherResult;
        }

        // Class slot conflict
        $classSectionId = $request->input('class_section_id');
        if ($classSectionId) {
            $classResult = TimetableConflictService::effectiveClassSlotTaken(
                $academicYearId, $termWeekId, (int) $classSectionId, $day, $periodId, $ignoreId
            );
            if ($classResult) {
                $conflicts['class_section'] = $classResult;
            }
        }

        // Classroom conflict
        $classroomId = $request->input('classroom_id');
        if ($classroomId) {
            $roomResult = TimetableConflictService::effectiveClassroomConflict(
                $academicYearId, $termWeekId, (int) $classroomId, $day, $periodId, $ignoreId
            );
            if ($roomResult) {
                $conflicts['classroom'] = $roomResult;
            }
        }

        // Teacher workload warnings
        $workloadWarnings = TimetableConflictService::checkTeacherWorkload(
            $teacherId, $academicYearId, $day, $ignoreId
        );
        if (!empty($workloadWarnings)) {
            $warnings['workload'] = $workloadWarnings;
        }

        return response()->json([
            'has_conflicts' => !empty($conflicts),
            'conflicts' => $conflicts,
            'warnings' => $warnings,
        ]);
    }

    /**
     * Store timetable overrides (cancel/substitute/reschedule) for a term week.
     */
    public function storeOverrides(Request $request)
    {
        $request->validate([
            'academic_year_id' => 'required|integer|exists:academic_years,academic_year_id',
            'term_week_id' => 'required|integer|exists:term_weeks,id',
            'overrides' => 'required|array|min:1',
            'overrides.*.timetable_id' => 'required|integer|exists:timetable,timetable_id',
            'overrides.*.override_type' => 'required|in:cancel,substitute,reschedule',
            'overrides.*.substitute_teacher_id' => 'nullable|exists:staff,staff_id',
            'overrides.*.substitute_classroom_id' => 'nullable|exists:classrooms,classroom_id',
            'overrides.*.new_day_of_week' => 'nullable|string|in:monday,tuesday,wednesday,thursday,friday,saturday,sunday',
            'overrides.*.new_period_id' => 'nullable|exists:periods,period_id',
            'overrides.*.new_teacher_id' => 'nullable|exists:staff,staff_id',
            'overrides.*.new_classroom_id' => 'nullable|exists:classrooms,classroom_id',
            'overrides.*.effective_date' => 'required|date',
            'overrides.*.reason' => 'nullable|string|max:255',
        ]);

        $academicYearId = (int) $request->input('academic_year_id');
        $termWeekId = (int) $request->input('term_week_id');
        $overrides = $request->input('overrides');
        $saved = 0;
        $errors = [];

        foreach ($overrides as $idx => $ov) {
            // Validate conditional reason requirement
            if (in_array($ov['override_type'], ['cancel', 'reschedule']) && empty($ov['reason'])) {
                $errors[] = "Override #" . ($idx + 1) . ": reason is required for {$ov['override_type']} overrides.";
                continue;
            }

            // Check for existing override on this timetable_id + term_week_id
            $existing = TimetableOverride::where('timetable_id', $ov['timetable_id'])
                ->where('term_week_id', $termWeekId)
                ->first();

            if ($existing) {
                $existing->update(array_merge($ov, [
                    'created_by' => auth()->id(),
                ]));
            } else {
                TimetableOverride::create(array_merge($ov, [
                    'created_by' => auth()->id(),
                ]));
            }
            $saved++;
        }

        if ($request->ajax() || $request->wantsJson()) {
            if (!empty($errors)) {
                return response()->json(['saved' => $saved, 'errors' => $errors], 422);
            }
            return response()->json(['saved' => $saved, 'message' => "Saved {$saved} override(s) for the selected week."]);
        }

        if (!empty($errors)) {
            Flash::warning("Saved {$saved} override(s). Issues: " . implode(' ', $errors));
        } else {
            Flash::success("Saved {$saved} override(s) for the selected week.");
        }

        return redirect()->back();
    }

